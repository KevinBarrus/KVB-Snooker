import * as B from "babylonjs/es6.js";
import { loadTexture } from "./assets.js";
import { requireMesh } from "./table.js";
import { buildFrame } from "./table-frame.js";
import { buildLeather, leatherTexture } from "./pocket-leather.js";
import { buildNet, linerMaterial, netMaterial } from "./pocket-net.js";
import { buildRunners } from "./pocket-runner.js";
import { reshapeMesh, type JawShift } from "./table-shape.js";
import { buildCushions, mapClothUV, retainClothBed, type CushionOutline } from "./table-cushions.js";
import { CINEMA_STYLE, CINEMA_TABLE_STYLE } from "./cinema-style.js";
import { cinemaClothMaterial, cinemaMaterial } from "./cinema-materials.js";
import { buildCinemaRoom } from "./cinema-room.js";
import { createCinemaPipeline } from "./cinema-pipeline.js";

export async function buildCinemaTable(scene: B.Scene, shift: JawShift, outline: CushionOutline): Promise<void> {
  for (const light of [...scene.lights]) light.dispose();
  for (const mesh of scene.meshes) mesh.setEnabled(false);
  scene.clearColor = new B.Color4(0.006, 0.007, 0.012, 1);
  createCinemaPipeline(scene);
  const style = CINEMA_TABLE_STYLE;
  const cloth = requireMesh(scene, "TableInner");
  cloth.setEnabled(true);
  reshapeMesh(cloth, shift);
  retainClothBed(cloth);
  mapClothUV(cloth);
  cloth.material = cinemaClothMaterial(scene);
  const cushions = buildCushions(outline).applyTo(new B.Mesh("cinema-cushions", scene));
  mapClothUV(cushions);
  cushions.material = cloth.material;
  const frame = buildFrame(style);
  const wood = cinemaMaterial(scene, "cinema-wood", style.railColor, style.railRoughness);
  wood.albedoTexture = await loadTexture(scene, "frame-diffuse");
  wood.albedoTexture.level = style.railBrightness;
  const trim = cinemaMaterial(scene, "cinema-brass", style.goldColor, style.goldRoughness, style.goldMetallic);
  const rail = frame.wood.applyTo(requireMesh(scene, "Frame"));
  rail.setEnabled(true); rail.material = wood;
  const rods = buildRunners(frame.gold, style).applyTo(new B.Mesh("PocketRunner", scene));
  rods.material = cinemaMaterial(scene, "cinema-runners", style.runnerColor, 0.5);
  frame.gold.applyTo(new B.Mesh("FrameGold", scene)).material = trim;
  const leather = buildLeather(shift, style).applyTo(requireMesh(scene, "Pocket"));
  leather.setEnabled(true);
  const leatherMat = cinemaMaterial(scene, "cinema-leather", style.leatherColor, 0.78);
  leatherMat.albedoTexture = leatherTexture(scene);
  leatherMat.backFaceCulling = false; leatherMat.twoSidedLighting = true;
  leather.material = leatherMat;
  const bags = buildNet(shift, style);
  bags.net.applyTo(new B.Mesh("PocketNet", scene)).material = netMaterial(scene, style);
  bags.liner.applyTo(new B.Mesh("PocketLiner", scene)).material = linerMaterial(scene, style);
  const room = buildCinemaRoom(scene);
  const key = new B.DirectionalLight("cinema-key", new B.Vector3(0.04, -1, 0.08), scene);
  key.intensity = CINEMA_STYLE.keyIntensity;
  key.excludedMeshes = room.meshes;
  const fill = new B.HemisphericLight("cinema-fill", B.Vector3.Up(), scene);
  fill.intensity = CINEMA_STYLE.fillIntensity;
  fill.groundColor.set(0.035, 0.045, 0.035);
  fill.excludedMeshes = room.meshes;
  const ambient = new B.HemisphericLight("cinema-room-light", B.Vector3.Up(), scene);
  ambient.intensity = CINEMA_STYLE.roomIntensity;
  ambient.groundColor.set(0.05, 0.045, 0.055);
  ambient.includedOnlyMeshes = room.meshes;
  const probe = new B.ReflectionProbe("cinema-reflections", 256, scene, true);
  probe.position.set(0, 0.90625, 0);
  probe.cubeTexture.renderList = room.meshes;
  probe.cubeTexture.gammaSpace = false;
  probe.refreshRate = B.RenderTargetTexture.REFRESHRATE_RENDER_ONCE;
  scene.customRenderTargets.push(probe.cubeTexture);
  scene.environmentTexture = probe.cubeTexture;
  scene.onDisposeObservable.add(() => probe.dispose());
}
